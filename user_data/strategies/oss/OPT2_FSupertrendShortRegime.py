"""
OPT2 (phase 2) — FSupertrendStrategy + BTC-regime-gated short side.

Base: user_data/strategies/oss/FSupertrendStrategy.py (original, untouched).
IS baseline of the original (20210101-20230101, 1h, BTC/ETH/SOL, fee
0.05%/side): 1026 trades, all long, +63.75%, maxDD 23.92%, Sharpe 0.86,
PF 1.08.

Phase-1 evidence (OPT1_FSupertrendStrategy, IS): enabling can_short with the
short side ungated gave 2022 bear-market shorts +4040 USDT but 2021 bull-market
shorts -6128 USDT -> net negative; OPT1 IS overall +23.03% (worse than base).

Hypothesis under test here: gate enter_short with a BTC regime filter so
shorts may only fire while BTC trades below its 1h EMA200 (bear regime),
keeping the 2022 short payoff and cutting the 2021 bull-market short losses.

Changes vs the ORIGINAL (ONLY these two; long side is a byte-for-byte copy):
  1. can_short = True
     (activates the enter_short/exit_short logic that already exists in the
     original source but never fired in futures mode).
  2. BTC regime gate on the SHORT side only:
     - informative_pairs() requests BTC/USDT:USDT 1h futures candles;
     - populate_indicators merges BTC close + a 200-period MA (default EMA;
       pandas ewm(span=200, adjust=False), value available from candle #1 so
       no NaN warm-up gap at backtest start given startup_candle_count=18)
       via merge_informative_pair (causal, candle-close aligned);
     - enter_short additionally requires btc_close_1h < btc_regime_ma_1h.
     exit_short (buy_m2 supertrend turns 'up') and the entire long side
     (params, ROI table, trailing, stoploss -0.265) are unchanged from the
     original.

regime_ma is a plain class attribute switch ("ema" default) used only for
the IS-internal EMA200-vs-SMA200 comparison; it is not a hyperopt space.
"""

import logging
from freqtrade.strategy import IStrategy, IntParameter, merge_informative_pair
from pandas import DataFrame
import pandas as pd
import talib.abstract as ta
import numpy as np

import technical.indicators as ftt

logger = logging.getLogger(__name__)


class OPT2_FSupertrendShortRegime(IStrategy):
    # Buy params, Sell params, ROI, Stoploss and Trailing Stop are values generated by 'freqtrade hyperopt --strategy Supertrend --hyperopt-loss ShortTradeDurHyperOptLoss --timerange=20210101- --timeframe=1h --spaces all'
    # It's encourage you find the values that better suites your needs and risk management strategies

    INTERFACE_VERSION: int = 3

    # OPT2 change #1: activate the (already coded) short side.
    can_short = True

    # Buy hyperspace params:
    buy_params = {
        "buy_m1": 4,
        "buy_m2": 7,
        "buy_m3": 1,
        "buy_p1": 8,
        "buy_p2": 9,
        "buy_p3": 8,
    }

    # Sell hyperspace params:
    sell_params = {
        "sell_m1": 1,
        "sell_m2": 3,
        "sell_m3": 6,
        "sell_p1": 16,
        "sell_p2": 18,
        "sell_p3": 18,
    }

    # ROI table: (original values, NOT the phase-1 retuned table)
    minimal_roi = {"0": 0.1, "30": 0.75, "60": 0.05, "120": 0.025}
    # minimal_roi = {"0": 1}

    # Stoploss:
    stoploss = -0.265

    # Trailing stop:
    trailing_stop = True
    trailing_stop_positive = 0.05
    trailing_stop_positive_offset = 0.1
    trailing_only_offset_is_reached = False

    timeframe = "1h"

    startup_candle_count = 18

    # --- OPT2 change #2: BTC regime gate configuration -------------------
    BTC_INFO_PAIR = "BTC/USDT:USDT"
    BTC_INFO_TF = "1h"
    REGIME_MA_PERIOD = 200
    # "ema" (hypothesis default) or "sma" — IS-internal comparison switch.
    regime_ma = "ema"
    # ----------------------------------------------------------------------

    buy_m1 = IntParameter(1, 7, default=1)
    buy_m2 = IntParameter(1, 7, default=3)
    buy_m3 = IntParameter(1, 7, default=4)
    buy_p1 = IntParameter(7, 21, default=14)
    buy_p2 = IntParameter(7, 21, default=10)
    buy_p3 = IntParameter(7, 21, default=10)

    sell_m1 = IntParameter(1, 7, default=1)
    sell_m2 = IntParameter(1, 7, default=3)
    sell_m3 = IntParameter(1, 7, default=4)
    sell_p1 = IntParameter(7, 21, default=14)
    sell_p2 = IntParameter(7, 21, default=10)
    sell_p3 = IntParameter(7, 21, default=10)

    def informative_pairs(self):
        # BTC 1h futures informative for the short-side regime gate.
        return [(self.BTC_INFO_PAIR, self.BTC_INFO_TF, "futures")]

    def populate_indicators(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        new_cols = []

        for multiplier in self.buy_m1.range:
            for period in self.buy_p1.range:
                new_cols.append(
                    self.supertrend_direction(
                        dataframe,
                        multiplier,
                        period,
                        f"supertrend_1_buy_{multiplier}_{period}",
                    )
                )

        for multiplier in self.buy_m2.range:
            for period in self.buy_p2.range:
                new_cols.append(
                    self.supertrend_direction(
                        dataframe,
                        multiplier,
                        period,
                        f"supertrend_2_buy_{multiplier}_{period}",
                    )
                )

        for multiplier in self.buy_m3.range:
            for period in self.buy_p3.range:
                new_cols.append(
                    self.supertrend_direction(
                        dataframe,
                        multiplier,
                        period,
                        f"supertrend_3_buy_{multiplier}_{period}",
                    )
                )

        for multiplier in self.sell_m1.range:
            for period in self.sell_p1.range:
                new_cols.append(
                    self.supertrend_direction(
                        dataframe,
                        multiplier,
                        period,
                        f"supertrend_1_sell_{multiplier}_{period}",
                    )
                )

        for multiplier in self.sell_m2.range:
            for period in self.sell_p2.range:
                new_cols.append(
                    self.supertrend_direction(
                        dataframe,
                        multiplier,
                        period,
                        f"supertrend_2_sell_{multiplier}_{period}",
                    )
                )

        for multiplier in self.sell_m3.range:
            for period in self.sell_p3.range:
                new_cols.append(
                    self.supertrend_direction(
                        dataframe,
                        multiplier,
                        period,
                        f"supertrend_3_sell_{multiplier}_{period}",
                    )
                )

        if new_cols:
            dataframe = pd.concat([dataframe] + new_cols, axis=1)

        # OPT2: BTC 1h regime informative (short gate only, long side untouched).
        btc = self.dp.get_pair_dataframe(self.BTC_INFO_PAIR, self.BTC_INFO_TF).copy()
        if self.regime_ma == "sma":
            ma = btc["close"].rolling(self.REGIME_MA_PERIOD).mean()
        else:  # "ema"
            ma = btc["close"].ewm(
                span=self.REGIME_MA_PERIOD, adjust=False
            ).mean()
        btc = btc[["date", "close"]].rename(columns={"close": "btc_close"})
        btc["btc_regime_ma"] = ma.to_numpy()
        dataframe = merge_informative_pair(
            dataframe, btc, self.timeframe, self.BTC_INFO_TF, ffill=True
        )

        return dataframe

    def populate_entry_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:

        dataframe.loc[
            (
                dataframe[f"supertrend_1_buy_{self.buy_m1.value}_{self.buy_p1.value}"]
                == "up"
            )
            & (
                dataframe[f"supertrend_2_buy_{self.buy_m2.value}_{self.buy_p2.value}"]
                == "up"
            )
            & (
                dataframe[f"supertrend_3_buy_{self.buy_m3.value}_{self.buy_p3.value}"]
                == "up"
            )
            & (  # The three indicators are 'up' for the current candle
                dataframe["volume"] > 0
            ),
            "enter_long",
        ] = 1

        dataframe.loc[
            (
                dataframe[
                    f"supertrend_1_sell_{self.sell_m1.value}_{self.sell_p1.value}"
                ]
                == "down"
            )
            & (
                dataframe[
                    f"supertrend_2_sell_{self.sell_m2.value}_{self.sell_p2.value}"
                ]
                == "down"
            )
            & (
                dataframe[
                    f"supertrend_3_sell_{self.sell_m3.value}_{self.sell_p3.value}"
                ]
                == "down"
            )
            & (  # The three indicators are 'down' for the current candle
                dataframe["volume"] > 0
            )
            & (  # OPT2 regime gate: shorts only while BTC < its 200-MA on 1h
                dataframe["btc_close_1h"] < dataframe["btc_regime_ma_1h"]
            ),
            "enter_short",
        ] = 1

        return dataframe

    def populate_exit_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        dataframe.loc[
            (
                dataframe[
                    f"supertrend_2_sell_{self.sell_m2.value}_{self.sell_p2.value}"
                ]
                == "down"
            ),
            "exit_long",
        ] = 1

        dataframe.loc[
            (
                dataframe[f"supertrend_2_buy_{self.buy_m2.value}_{self.buy_p2.value}"]
                == "up"
            ),
            "exit_short",
        ] = 1

        return dataframe

    def supertrend_direction(
        self, dataframe: DataFrame, multiplier: int, period: int, name: str
    ) -> pd.Series:
        """
        Supertrend direction ('up' / 'down') as a named series.
        `ftt.supertrend` returns a (value, direction) tuple - only the direction is used here.
        """
        _, stx = ftt.supertrend(dataframe, period=period, multiplier=multiplier)
        # 'stx' is None before the indicator has warmed up - keep the empty string
        return pd.Series(stx, index=dataframe.index, name=name).fillna("")
