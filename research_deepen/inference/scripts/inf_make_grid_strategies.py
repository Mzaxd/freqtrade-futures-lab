"""inf_make_grid_strategies.py — generate the 75 CSCV/PBO grid strategy files.

Writes one file per cell into research_deepen/inference/strategies/grid/:
    class INF_G_s{sig*10}_t{stop*10}_r{rh}(OPT4_VolatilitySystem)
with signal_atr_mult / stop_atr_mult / resample_hours pinned to the cell value.

Why one file per class: freqtrade 2026.8's StrategyResolver only considers a
.py file when it literally contains the text `class <Name>(` (a type() factory
at module scope is invisible to it). Everything else inherits the frozen
OPT4_VolatilitySystem (atr08 gate, 60d time stop, 1%-risk sizing, 2x lev).

Frozen champion cell = s20_t20_r3 (2.0 / 2.0 / 3h).
"""
from __future__ import annotations

import os

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
DEST = os.path.join(REPO, "research_deepen", "inference", "strategies", "grid")

TEMPLATE = '''# Auto-generated by inf_make_grid_strategies.py (CSCV/PBO grid cell).
# signal_atr_mult={sig} / stop_atr_mult={stop} / resample_hours={rh}
import os as _os
import sys as _sys

_OSS = _os.path.abspath(
    _os.path.join(_os.path.dirname(__file__), "..", "..", "..", "..", "user_data", "strategies", "oss")
)
if _OSS not in _sys.path:
    _sys.path.insert(0, _OSS)

from freqtrade.strategy import DecimalParameter, IntParameter  # noqa: E402

from OPT4_VolatilitySystem import OPT4_VolatilitySystem  # noqa: E402


class {name}(OPT4_VolatilitySystem):
    signal_atr_mult = DecimalParameter(1.0, 4.0, default={sig}, decimals=1, space="buy")
    stop_atr_mult = DecimalParameter(1.0, 4.0, default={stop}, decimals=1, space="sell")
    resample_hours = IntParameter(2, 6, default={rh}, space="buy")
'''

SIGNAL_GRID = [1.6, 1.8, 2.0, 2.2, 2.4]
STOP_GRID = [1.6, 1.8, 2.0, 2.2, 2.4]
RESAMPLE_GRID = [2, 3, 4]


def main() -> None:
    os.makedirs(DEST, exist_ok=True)
    n = 0
    for sig in SIGNAL_GRID:
        for stop in STOP_GRID:
            for rh in RESAMPLE_GRID:
                tag = f"s{int(round(sig * 10)):02d}_t{int(round(stop * 10)):02d}_r{rh}"
                name = f"INF_G_{tag}"
                path = os.path.join(DEST, f"{name}.py")
                with open(path, "w") as f:
                    f.write(TEMPLATE.format(name=name, sig=sig, stop=stop, rh=rh))
                n += 1
    print(f"wrote {n} grid strategy files to {DEST}")


if __name__ == "__main__":
    main()
